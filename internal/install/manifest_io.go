package install

import (
	"bytes"
	"errors"
	"io/fs"
	"os"
	"path/filepath"

	"gopkg.in/yaml.v3"

	"github.com/bestagentkits/sisf/pkg/manifest"
)

const manifestHeader = `# Manifest of one SISF factory deployment, generated by "sisf init".
#
# This file is desired state approved by the Owner. It holds references to
# secrets (env:NAME or local:path/name), never the secrets themselves. The
# digests are filled in by "sisf up" from the artifacts it builds; a digest
# made only of zeros marks an artifact that has not been built yet.
#
# Check it with:  sisf conformance check <this file>
`

// simManifestNote heads the manifest of the simulation profile, whose
// adapters name real agent backends only so the release rules are checked
// as they will be for a real install.
const simManifestNote = `#
# Simulation profile: adapters.coder and adapters.qa name the agent backends
# the deployment rules are checked against. The simulation does not run
# them: it runs the scripted agent and the scripted judge, calls no model
# provider and spends nothing.
`

// writeManifest writes factory.yaml for the owner and the group.
func writeManifest(path string, m *manifest.Manifest) error {
	var buf bytes.Buffer
	buf.WriteString(manifestHeader)
	if m.Extensions["profile"] == profileSim {
		buf.WriteString(simManifestNote)
	}
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(m); err != nil {
		return invalidf("the manifest cannot be encoded: %v", err)
	}
	if err := enc.Close(); err != nil {
		return invalidf("the manifest cannot be encoded: %v", err)
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return unavailablef(err, "cannot create the install directory")
	}
	// The manifest holds no secret, so a new one is readable by the
	// containers that mount it, which run as another user; one the Owner
	// restricted keeps its mode.
	mode := fs.FileMode(0o644)
	if info, err := os.Stat(path); err == nil {
		mode = info.Mode().Perm()
	} else if !errors.Is(err, fs.ErrNotExist) {
		return unavailablef(err, "cannot read %s", path)
	}
	old, err := os.ReadFile(path)
	switch {
	case err == nil && bytes.Equal(old, buf.Bytes()):
		return nil
	case err == nil && m.Mode == manifest.ModeDocker:
		// The containers mount this one file, and a mount follows the file
		// it was made from, not the name: a manifest renamed into place
		// would leave every running container reading the old one.
		return rewriteMountedFile(path, buf.Bytes())
	}
	return replaceFile(path, buf.Bytes(), mode)
}

// rewriteMountedFile writes data into the file path already names and syncs
// it. It is not atomic: a crash can leave a cut manifest, which does not
// parse and is written again by the next "sisf up".
func rewriteMountedFile(path string, data []byte) error {
	f, err := os.OpenFile(path, os.O_WRONLY|os.O_TRUNC, 0)
	if err != nil {
		return unavailablef(err, "cannot write %s", path)
	}
	_, err = f.Write(data)
	if err == nil {
		err = f.Sync()
	}
	if err = errors.Join(err, f.Close()); err != nil {
		return unavailablef(err, "cannot write %s", path)
	}
	return nil
}

// replaceFile writes data to path with mode as a whole: to a new file
// beside it, synced to disk, renamed over path, and the directory synced,
// so a crash or a full disk leaves the old file or the new one, never a
// cut one.
func replaceFile(path string, data []byte, mode fs.FileMode) error {
	dir := filepath.Dir(path)
	tmp, err := os.CreateTemp(dir, "."+filepath.Base(path)+".tmp-*")
	if err != nil {
		return unavailablef(err, "cannot create a file in %s", dir)
	}
	defer func() { _ = os.Remove(tmp.Name()) }() // gone after a successful rename; cleanup after a failure
	if err := writeSynced(tmp, data, mode); err != nil {
		return unavailablef(err, "cannot write %s", path)
	}
	if err := os.Rename(tmp.Name(), path); err != nil {
		return unavailablef(err, "cannot place %s", path)
	}
	d, err := os.Open(dir)
	if err != nil {
		return unavailablef(err, "cannot sync %s", dir)
	}
	defer func() { _ = d.Close() }()
	if err := d.Sync(); err != nil {
		return unavailablef(err, "cannot sync %s", dir)
	}
	return nil
}

// writeSynced sets f's mode, writes data to it, syncs it to disk and
// closes it.
func writeSynced(f *os.File, data []byte, mode fs.FileMode) error {
	err := f.Chmod(mode)
	if err == nil {
		_, err = f.Write(data)
	}
	if err == nil {
		err = f.Sync()
	}
	return errors.Join(err, f.Close())
}

// installed reports whether a manifest exists in the install directory.
func (l Layout) installed() (bool, error) {
	_, err := os.Stat(l.Config())
	if errors.Is(err, fs.ErrNotExist) {
		return false, nil
	}
	return err == nil, err
}

// LoadManifest reads the install's manifest.
func (l Layout) LoadManifest() (*manifest.Manifest, error) { return manifest.ParseFile(l.Config()) }

// SaveManifest writes m as the install's manifest, in the form sisf init
// writes it. A manifest that departs from the schema is not written.
func (l Layout) SaveManifest(m *manifest.Manifest) error {
	if found := manifest.Validate(m); len(found) != 0 {
		return invalidf("the manifest is not valid: %s", found[0])
	}
	return writeManifest(l.Config(), m)
}
